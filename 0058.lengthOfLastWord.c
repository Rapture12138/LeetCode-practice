int lengthOfLastWord(char* s) {
    int len = 0; // 记录最后一个单词的长度
    char* p = s; // 指针指向字符串起始位置

    // 第一步：先让指针走到字符串末尾（找到'\0'）
    while (*p != '\0') {
        p++;
    }
    // 此时p指向'\0'，需要回退到最后一个有效字符的位置
    p--;

    // 第二步：跳过末尾的所有空格（处理"hello world  "这类情况）
    while (p >= s && *p == ' ') {
        p--;
    }

    // 第三步：统计最后一个单词的长度（直到遇到空格或字符串开头）
    while (p >= s && *p != ' ') {
        len++;
        p--;
    }

    return len;
}
